#!/usr/bin/env node
/**
 * Generate an Ollama Modelfile that pins a base model to a LoRA adapter.
 *
 * Usage:
 *   node scripts/finetune/build-modelfile.js \
 *       --base llama3.2 \
 *       --adapter ./data/adapters/v1.gguf \
 *       --out ./data/adapters/v1.Modelfile \
 *       [--tag vanaila-llama:v1] \
 *       [--system "Custom system prompt"]
 *
 * After it writes the Modelfile, register the model with Ollama:
 *   ollama create vanaila-llama:v1 -f ./data/adapters/v1.Modelfile
 *
 * Then pick the new tag from VanailaChat's model selector. The backend
 * sees it via Ollama's normal /api/tags listing — no extra wiring.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

function parseArgs(argv) {
  const out = {};
  for (let i = 2; i < argv.length; i++) {
    const arg = argv[i];
    if (!arg.startsWith('--')) continue;
    const key = arg.slice(2);
    const value = argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[i + 1] : 'true';
    out[key] = value;
    if (value !== 'true') i++;
  }
  return out;
}

function usage() {
  console.error('Usage: build-modelfile.js --base <model> --adapter <path> --out <Modelfile> [--tag <name:tag>] [--system <prompt>]');
  process.exit(2);
}

async function main() {
  const args = parseArgs(process.argv);
  const base = args.base;
  const adapter = args.adapter;
  const out = args.out;
  const tag = args.tag ?? null;
  const system =
    args.system ??
    'You are a helpful local assistant fine-tuned on the user\'s own positively-rated conversations. Match their preferred tone and depth. Be honest when uncertain.';

  if (!base || !adapter || !out) usage();

  const adapterAbs = path.resolve(adapter);
  try {
    await fs.access(adapterAbs);
  } catch {
    console.error(`adapter file not found: ${adapterAbs}`);
    process.exit(1);
  }

  const lines = [
    `# Generated by VanailaChat fine-tune harness on ${new Date().toISOString()}`,
    `FROM ${base}`,
    ``,
    `# LoRA adapter trained from message_feedback rating = 1 dataset.`,
    `ADAPTER ${adapterAbs}`,
    ``,
    `SYSTEM """${system.replace(/"""/g, '\\"\\"\\"')}"""`,
    ``,
    `# Reasonable defaults; tune per use case.`,
    `PARAMETER temperature 0.7`,
    `PARAMETER top_p 0.9`,
    `PARAMETER repeat_penalty 1.1`,
    ``,
  ].join('\n');

  await fs.mkdir(path.dirname(out), { recursive: true });
  await fs.writeFile(out, lines, 'utf8');

  console.log(`wrote ${out}`);
  if (tag) {
    console.log(`\nnext: ollama create ${tag} -f ${out}`);
  } else {
    console.log(`\nnext: ollama create <name:tag> -f ${out}`);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
